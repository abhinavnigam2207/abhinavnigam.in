// Builds the dot grids the travel page draws its globe and maps from: one bit per grid cell, set where there
// is land. Run once with `pnpm exec tsx scripts/build-land-mask.ts`; the output file is committed, so the
// site needs no map library or map tiles at run time.
//
// No borders are stored or drawn: the grids hold land and sea only.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"));
const land = feature(topology, topology.objects.land);

type Grid = { west: number; north: number; step: number; cols: number; rows: number };

function mask({ west, north, step, cols, rows }: Grid) {
  const bytes = new Uint8Array(Math.ceil((cols * rows) / 8));
  for (let row = 0; row < rows; row++) {
    for (let col = 0; col < cols; col++) {
      // Sample the centre of each cell.
      const point: [number, number] = [west + (col + 0.5) * step, north - (row + 0.5) * step];
      if (geoContains(land as never, point)) bytes[(row * cols + col) >> 3] |= 1 << ((row * cols + col) & 7);
    }
  }
  return { west, north, step, cols, rows, bits: Buffer.from(bytes).toString("base64") };
}

const world = mask({ west: -180, north: 90, step: 1.5, cols: 240, rows: 120 });
// South Asia at finer grain, for the zoomed-in India chapter.
const southAsia = mask({ west: 60, north: 40, step: 0.4, cols: 105, rows: 90 });

writeFileSync("client/src/content/landMask.ts", `// Generated by scripts/build-land-mask.ts. Do not edit.
export type LandMask = { west: number; north: number; step: number; cols: number; rows: number; bits: string };

export const worldMask: LandMask = ${JSON.stringify(world)};

export const southAsiaMask: LandMask = ${JSON.stringify(southAsia)};
`, "utf8");
console.log(`world ${world.bits.length} chars, south asia ${southAsia.bits.length} chars`);
